"""Create synthetic local footage and exercise actual FFmpeg candidate and render paths."""

from __future__ import annotations

import io
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def find_executable(variable: str, command: str) -> str | None:
    """Resolve a user-configured tool or a standard PATH installation."""
    configured = os.environ.get(variable, "").strip()
    if configured and Path(configured).is_file():
        return str(Path(configured).resolve())
    return shutil.which(configured or command)


def wait_for_job(core, job_id: str, timeout_seconds: int = 240):
    """Wait for the real background render to reach a durable terminal state."""
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline:
        job = core.get_job(job_id)
        if job["status"] in {"review", "failed", "cancelled"}:
            return job
        time.sleep(0.25)
    raise AssertionError("Render exceeded its integration-test timeout.")


def rgb_sample(ffmpeg: str, media: Path, seconds: float) -> tuple[int, int, int]:
    """Decode one scaled RGB pixel to check source-time selection and timeline segment order."""
    result = subprocess.run([ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-ss", str(seconds),
        "-i", str(media), "-frames:v", "1", "-vf", "scale=1:1:flags=area", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
        check=True, capture_output=True, timeout=30)
    assert len(result.stdout) == 3
    return tuple(result.stdout)


def main() -> None:
    """Run both fixed output profiles without network access or user footage."""
    ffmpeg, ffprobe = find_executable("VSF_FFMPEG", "ffmpeg"), find_executable("VSF_FFPROBE", "ffprobe")
    if not ffmpeg or not ffprobe:
        raise SystemExit("SKIP: set VSF_FFMPEG and VSF_FFPROBE or put both executables on PATH.")
    os.environ["VSF_FFMPEG"], os.environ["VSF_FFPROBE"] = ffmpeg, ffprobe
    with tempfile.TemporaryDirectory(prefix="clipforge-phase2-", dir=ROOT / "tests") as temporary:
        workspace = Path(temporary)
        os.environ["VSF_DATA_DIR"] = str(workspace / "ClipForge data with spaces")
        from app import main as core

        source_path = workspace / "Synthetic scene source with spaces.mp4"
        generate = [ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
                    "-f", "lavfi", "-i", "color=c=red:s=320x240:r=24:d=8",
                    "-f", "lavfi", "-i", "color=c=blue:s=320x240:r=24:d=8",
                    "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=44100:duration=16",
                    "-filter_complex", "[0:v][1:v]concat=n=2:v=1:a=0[v];"
                    "[2:a]volume=enable='between(t,4,6)':volume=0[a]",
                    "-map", "[v]", "-map", "[a]", "-c:v", "libx264", "-preset", "ultrafast",
                    "-pix_fmt", "yuv420p", "-c:a", "aac", str(source_path)]
        subprocess.run(generate, check=True, timeout=90)
        metadata = core.probe_media(source_path)
        assert metadata and metadata["duration"] == 16 and metadata["has_audio"]
        analysis = core.analyze_source(source_path, metadata["duration"], metadata["has_audio"])
        assert analysis["scene_times"] and analysis["silence_intervals"], analysis

        with source_path.open("rb") as source:
            asset = core.import_local_file(source_path.name, source, str(source_path.stat().st_size))
        creator = core.create_creator({"name": "Synthetic integration creator"})
        core.record_permission(asset["id"], {"creator_id": creator["id"], "status": "granted",
                                              "evidence": "Synthetic footage generated by this test"})
        assert core.inspect_asset(asset["id"])["status"] == "inspected"
        found = core.discover_candidates(asset["id"], {"content_preset": "custom", "minimum_seconds": 3,
            "maximum_seconds": 8, "padding_before": 1, "padding_after": 1})
        assert found["candidates"] and found["candidates"][0]["status"] == "pending"
        candidate = found["candidates"][0]
        accepted = core.update_candidate(candidate["id"], {"decision": "accepted", "title": "Scene transition",
            "hook": "A clear color change", "notes": "Synthetic scene change; inspect timing.",
            "start_seconds": candidate["start_seconds"], "end_seconds": candidate["end_seconds"],
            "profile": "short_vertical", "content_preset": "custom"})
        project_id = accepted["project_id"]
        assert project_id
        subtitles = "1\n00:00:00,000 --> 00:00:01,000\nSynthetic caption — café"
        core.update_edit_project(project_id, {"title": "Shorts timeline with spaces", "profile": "short_vertical",
            "segments": [{"start_seconds": 10, "end_seconds": 13}, {"start_seconds": 1, "end_seconds": 4}],
            "captions_srt": subtitles})
        short = core.queue_project_render(project_id)
        short_job = wait_for_job(core, short["id"])
        assert short_job["status"] == "review", short_job.get("diagnostic")
        short_info = core.probe_output(core.OUTPUT_ROOT / short_job["output_path"])
        assert short_info and (short_info["width"], short_info["height"]) == (1080, 1920)
        assert 5 <= short_info["duration"] <= 7 and short_info["has_audio"]
        first_segment_color = rgb_sample(ffmpeg, core.OUTPUT_ROOT / short_job["output_path"], 1.0)
        second_segment_color = rgb_sample(ffmpeg, core.OUTPUT_ROOT / short_job["output_path"], 4.5)
        assert first_segment_color[2] > first_segment_color[0] * 2, first_segment_color
        assert second_segment_color[0] > second_segment_color[2] * 2, second_segment_color
        core.review_job(short_job["id"], {"decision": "approved", "notes": "Synthetic local smoke test only."})
        assert core.get_edit_project(project_id)["review_status"] == "approved"
        assert core.list_edit_project_reviews(project_id)[0]["decision"] == "approved"

        long_project = core.create_edit_project(asset["id"], {"title": "Widescreen timeline", "profile": "long_horizontal",
            "content_preset": "educational", "segments": [{"start_seconds": 2, "end_seconds": 8}],
            "captions_srt": subtitles})
        long_job_result = core.queue_project_render(long_project["id"])
        long_job = wait_for_job(core, long_job_result["id"])
        assert long_job["status"] == "review", long_job.get("diagnostic")
        long_info = core.probe_output(core.OUTPUT_ROOT / long_job["output_path"])
        assert long_info and (long_info["width"], long_info["height"]) == (1920, 1080)
        assert 5 <= long_info["duration"] <= 7 and long_info["has_audio"]
        print("PASS: synthetic source with spaces, FFprobe metadata, scene and silence analysis, candidate review,")
        print("      persistent multi-segment Shorts render with Unicode captions and source audio, and widescreen render.")
        print("PASS: both drafts reached human review; one was explicitly approved in the isolated temporary database.")
        print("CLEANUP: temporary sources, database, logs, and render outputs removed on exit.")


if __name__ == "__main__":
    main()
